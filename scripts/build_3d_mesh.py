#!/usr/bin/env python3
"""Generate a real torus-knot mesh and its animated README preview."""

from __future__ import annotations

import math
from pathlib import Path
from typing import TypeAlias

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
MODELS = ASSETS / "models"

Vec3: TypeAlias = tuple[float, float, float]
Face: TypeAlias = tuple[int, int, int]

RINGS = 96
SIDES = 18
MAJOR_RADIUS = 2.25
MINOR_RADIUS = 0.78
TUBE_RADIUS = 0.22


def add(a: Vec3, b: Vec3) -> Vec3:
    """Add two vectors."""
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def subtract(a: Vec3, b: Vec3) -> Vec3:
    """Subtract two vectors."""
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def scale(vector: Vec3, amount: float) -> Vec3:
    """Scale a vector."""
    return tuple(component * amount for component in vector)  # type: ignore[return-value]


def dot(a: Vec3, b: Vec3) -> float:
    """Return the vector dot product."""
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def cross(a: Vec3, b: Vec3) -> Vec3:
    """Return the vector cross product."""
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def normalize(vector: Vec3) -> Vec3:
    """Normalize a non-zero vector."""
    length = math.sqrt(dot(vector, vector))
    if length < 1e-12:
        raise ValueError("Cannot normalize a zero-length vector")
    return scale(vector, 1.0 / length)


def centerline(t: float) -> Vec3:
    """Return a point on a (2, 3) torus knot."""
    radial = MAJOR_RADIUS + MINOR_RADIUS * math.cos(3 * t)
    return (
        radial * math.cos(2 * t),
        radial * math.sin(2 * t),
        MINOR_RADIUS * math.sin(3 * t),
    )


def tangent(t: float) -> Vec3:
    """Approximate the knot tangent with a centred finite difference."""
    delta = 1e-4
    return normalize(subtract(centerline(t + delta), centerline(t - delta)))


def build_mesh() -> tuple[list[Vec3], list[Face]]:
    """Create the closed tube mesh around the knot centerline."""
    vertices: list[Vec3] = []
    frames: list[tuple[Vec3, Vec3]] = []
    previous_normal: Vec3 | None = None

    for ring in range(RINGS):
        t = math.tau * ring / RINGS
        direction = tangent(t)
        if previous_normal is None:
            reference = (0.0, 0.0, 1.0)
            normal = normalize(cross(direction, reference))
        else:
            transported = subtract(
                previous_normal, scale(direction, dot(previous_normal, direction))
            )
            normal = normalize(transported)
        binormal = normalize(cross(direction, normal))
        frames.append((normal, binormal))
        previous_normal = normal

    for ring, (normal, binormal) in enumerate(frames):
        t = math.tau * ring / RINGS
        center = centerline(t)
        for side in range(SIDES):
            angle = math.tau * side / SIDES
            offset = add(
                scale(normal, TUBE_RADIUS * math.cos(angle)),
                scale(binormal, TUBE_RADIUS * math.sin(angle)),
            )
            vertices.append(add(center, offset))

    faces: list[Face] = []
    for ring in range(RINGS):
        next_ring = (ring + 1) % RINGS
        for side in range(SIDES):
            next_side = (side + 1) % SIDES
            a = ring * SIDES + side
            b = next_ring * SIDES + side
            c = next_ring * SIDES + next_side
            d = ring * SIDES + next_side
            faces.extend([(a, b, c), (a, c, d)])
    return vertices, faces


def face_normal(vertices: list[Vec3], face: Face) -> Vec3:
    """Calculate one triangle normal."""
    a, b, c = (vertices[index] for index in face)
    return normalize(cross(subtract(b, a), subtract(c, a)))


def write_stl(vertices: list[Vec3], faces: list[Face]) -> None:
    """Write an ASCII STL that GitHub and modelling tools can inspect."""
    lines = ["solid curiosity_knot"]
    for face in faces:
        normal = face_normal(vertices, face)
        lines.append(f"  facet normal {normal[0]:.7f} {normal[1]:.7f} {normal[2]:.7f}")
        lines.append("    outer loop")
        for index in face:
            vertex = vertices[index]
            lines.append(f"      vertex {vertex[0]:.7f} {vertex[1]:.7f} {vertex[2]:.7f}")
        lines.extend(["    endloop", "  endfacet"])
    lines.append("endsolid curiosity_knot")
    (MODELS / "curiosity-knot.stl").write_text("\n".join(lines) + "\n", encoding="ascii")


def write_obj(vertices: list[Vec3], faces: list[Face]) -> None:
    """Write the same mesh as a portable Wavefront OBJ."""
    lines = ["# Curiosity Knot - generated by scripts/build_3d_mesh.py", "o CuriosityKnot"]
    lines.extend(f"v {x:.7f} {y:.7f} {z:.7f}" for x, y, z in vertices)
    lines.extend(f"f {a + 1} {b + 1} {c + 1}" for a, b, c in faces)
    (MODELS / "curiosity-knot.obj").write_text("\n".join(lines) + "\n", encoding="ascii")


def project(vertex: Vec3, yaw: float, pitch: float) -> tuple[float, float]:
    """Project a rotated 3D vertex into the wireframe viewport."""
    x, y, z = vertex
    x1 = math.cos(yaw) * x - math.sin(yaw) * y
    y1 = math.sin(yaw) * x + math.cos(yaw) * y
    y2 = math.cos(pitch) * y1 - math.sin(pitch) * z
    z2 = math.sin(pitch) * y1 + math.cos(pitch) * z
    perspective = 1.0 / (1.0 + 0.055 * z2)
    return (600 + x1 * 137 * perspective, 272 - y2 * 137 * perspective)


def path(points: list[tuple[float, float]], close: bool = False) -> str:
    """Convert projected points to a compact SVG path."""
    commands = [f"M{points[0][0]:.1f} {points[0][1]:.1f}"]
    commands.extend(f"L{x:.1f} {y:.1f}" for x, y in points[1:])
    if close:
        commands.append("Z")
    return "".join(commands)


def wireframe_group(vertices: list[Vec3], yaw: float, phase: int) -> str:
    """Build one projected mesh phase used by the cross-fade animation."""
    projected = [project(vertex, yaw, -0.48) for vertex in vertices]
    paths: list[str] = []
    for ring in range(0, RINGS, 3):
        points = [projected[ring * SIDES + side] for side in range(SIDES)]
        paths.append(f'<path d="{path(points, close=True)}"/>')
    for side in range(0, SIDES, 2):
        points = [projected[ring * SIDES + side] for ring in range(RINGS)]
        paths.append(f'<path d="{path(points, close=True)}"/>')
    return f'<g class="mesh phase{phase}">{"".join(paths)}</g>'


