def main() -> None:
    """Generate the mesh formats and animated wireframe preview."""
    MODELS.mkdir(parents=True, exist_ok=True)
    vertices, faces = build_mesh()
    write_stl(vertices, faces)
    write_obj(vertices, faces)
    write_preview(vertices)
    print(f"Generated {len(vertices)} vertices and {len(faces)} faces in STL, OBJ, and SVG formats")


if __name__ == "__main__":
    main()
